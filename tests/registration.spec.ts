async function noOverflow(page: Page) { expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true) }
async function account(page: Page, email = 'liza@example.test') {
  await page.goto('/register')
  await page.getByLabel('Имя', { exact: true }).fill('Лиза')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Пароль', { exact: true }).fill('MyTestPassword2026')
  await page.getByRole('button', { name: 'Продолжить', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Когда ты родился?', exact: true })).toBeVisible()
}
async function birthday(page: Page, year = '2010', month = '4', day = '12') {
  await page.getByRole('combobox', { name: 'День', exact: true }).selectOption(day)
  await page.getByRole('combobox', { name: 'Месяц', exact: true }).selectOption(month)
  await page.getByRole('combobox', { name: 'Год', exact: true }).selectOption(year)
  await page.getByRole('button', { name: 'Продолжить', exact: true }).click()
}
async function schoolAndClass(page: Page) {
  await page.getByRole('button', { name: /ГБОУ школа №123/ }).click()
  await page.getByRole('button', { name: 'Это моя школа', exact: true }).click()
  await page.getByRole('button', { name: '9', exact: true }).click()
  await page.getByRole('button', { name: 'Б', exact: true }).click()
  await page.getByRole('button', { name: 'Присоединиться к 9Б', exact: true }).click()
}
async function accept(page: Page) {
  await page.getByRole('checkbox', { name: /Я принимаю правила сообщества и условия использования/ }).check()
  await page.getByRole('button', { name: 'Войти в Маяк', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Добро пожаловать в 9Б', exact: true })).toBeVisible()
}

