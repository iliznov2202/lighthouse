test('failed registration storage keeps the form recoverable without creating a partial account', async ({ page }) => {
  await account(page); await birthday(page); await schoolAndClass(page)
  await page.getByRole('button', { name: 'Готово', exact: true }).click()
  await page.evaluate(() => {
    const original = Storage.prototype.setItem
    Storage.prototype.setItem = function(key: string, value: string) { if (key === 'mayak-mock-accounts-v1') throw new DOMException('Full', 'QuotaExceededError'); return original.call(this, key, value) }
  })
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Войти в Маяк', exact: true }).click()
  await expect(page.getByText(/Браузер не смог сохранить аккаунт/)).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('mayak-registration-pending-v1'))).toBeNull()
  await page.getByRole('button', { name: 'Назад', exact: true }).click()
  await expect(page.getByLabel('Username', { exact: true })).toHaveValue('liza_m')
})

test('birthday boundaries, leap days and username suggestions', () => {
  expect(ageOn('2012-10-01', '2026-10-01')).toBe(14)
  expect(ageOn('2012-10-02', '2026-10-01')).toBe(13)
  expect(ageOn('2008-10-01', '2026-10-01')).toBe(18)
  expect(validateBirthDate({ day: '29', month: '2', year: '2012' }, '2026-10-01')).toBeNull()
  expect(validateBirthDate({ day: '29', month: '2', year: '2011' }, '2026-10-01')).toContain('Такой даты нет')
  expect(suggestUsername('Лиза')).toBe('liza_m')
})

