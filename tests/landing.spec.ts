import { expect, test, type Page } from '@playwright/test'
test.setTimeout(60000)

async function noOverflow(page: Page) { expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy() }
async function fitsViewport(page: Page) {
  const card = page.locator('.ml-game-card')
  const bounds = await card.boundingBox()
  expect(bounds).not.toBeNull()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.y).toBeGreaterThanOrEqual(70)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(await page.evaluate(() => innerHeight))
}
async function lightLighthouse(page: Page, checkFit = false) {
  const initialUrl = page.url()
  await page.getByRole('button', { name: 'Зажечь маяк', exact: true }).click()
  await expect(page.getByRole('heading', { name: /Какую планету/ })).toBeFocused()
  if (checkFit) await fitsViewport(page)
  await page.getByRole('button', { name: /Венера/ }).click()
  await expect(page.getByRole('status')).toContainText('Попробуй ещё', { ignoreCase: true })
  await expect(page.getByLabel('0 / 3 искры')).toBeVisible()
  await page.getByRole('button', { name: /Марс/ }).click()
  await expect(page.getByLabel('1 / 3 искры')).toBeVisible()
  await expect(page.locator('.ml-main-beacon .lighthouse-window-one')).toHaveCSS('opacity', '0.9')
  await expect(page.getByRole('heading', { name: 'Поймай 3 звезды' })).toBeFocused()
  if (checkFit) await fitsViewport(page)
  const positions = []
  for (let index = 1; index <= 3; index++) {
    const star = page.getByRole('button', { name: `Поймать звезду ${index}` })
    await expect(star).not.toHaveClass(/is-caught/)
    const target = (await star.boundingBox())!
    const arena = (await page.locator('.ml-star-arena').boundingBox())!
    expect(target.width).toBeGreaterThanOrEqual(44)
    expect(target.height).toBeGreaterThanOrEqual(44)
    expect(target.x - arena.x).toBeGreaterThanOrEqual(7)
    expect(target.y - arena.y).toBeGreaterThanOrEqual(7)
    expect(arena.x + arena.width - target.x - target.width).toBeGreaterThanOrEqual(7)
    expect(arena.y + arena.height - target.y - target.height).toBeGreaterThanOrEqual(7)
    positions.push(await star.getAttribute('style'))
    await star.click()
    await expect(page.locator('.ml-star-count')).toHaveText(`${index} / 3`)
  }
  expect(new Set(positions).size).toBeGreaterThan(1)
  await expect(page.getByRole('heading', { name: 'Что зажигает твой интерес?' })).toBeFocused()
  if (checkFit) await fitsViewport(page)
  await expect(page.getByLabel('2 / 3 искры')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Готово', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: /Квизы Узнавать/ }).click()
  await page.getByRole('button', { name: /Творчество Выражать/ }).click()
  await expect(page.getByRole('button', { name: /Квизы Узнавать/ })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: /Творчество Выражать/ }).click()
  await expect(page.getByRole('button', { name: /Творчество Выражать/ })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: 'Готово', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Маяк зажжён!' })).toBeFocused()
  if (checkFit) await fitsViewport(page)
  await expect(page.getByTestId('lighthouse')).toHaveAttribute('data-sparks', '3')
  await expect(page.getByLabel('3 / 3 искры')).toBeVisible()
  await expect(page.locator('.ml-earned')).toContainText('+30')
  await expect(page.locator('.ml-profile-preview')).toContainText('Новичок')
  await expect(page.locator('.ml-main-beacon .lighthouse-beam')).toHaveCSS('opacity', '1')
  expect(page.url()).toBe(initialUrl)
}
