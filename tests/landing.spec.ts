test('landing: three games, shared profile card and registration into the app', async ({ page }) => {
  const errors: string[] = []
  const backendRequests: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (/\/(auth|users|schools|classes)(\/|\?)/.test(request.url())) backendRequests.push(request.url()) })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /Зажги свой/ })).toBeVisible()
  await noOverflow(page)
  await page.screenshot({ path: `artifacts/landing-hero-${test.info().project.name}.png`, animations: 'disabled' })
  await lightLighthouse(page)
  await page.screenshot({ path: `artifacts/landing-completed-${test.info().project.name}.png`, animations: 'disabled' })
  await page.getByRole('link', { name: 'Создать профиль', exact: true }).click()
  await expect(page).toHaveURL(/\/register$/)
  await expect(page.getByTestId('intro-reward')).toContainText('+30 очков')
  await page.screenshot({ path: `artifacts/landing-register-${test.info().project.name}.png`, fullPage: true, animations: 'disabled' })
  await registerProfile(page)
  await expect(page).toHaveURL(/\/demo$/)
  await expect(page.getByRole('heading', { name: /Привет, Искра/ })).toBeVisible()
  expect(await page.evaluate(() => JSON.stringify(localStorage) + JSON.stringify(sessionStorage))).not.toContain('demo-password-123')
  expect(backendRequests).toEqual([])
  expect(errors).toEqual([])
  await noOverflow(page)
})
