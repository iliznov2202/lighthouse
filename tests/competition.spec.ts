import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
import { knowledgeQuiz, weeklyCompetition, initialClassRankings } from '../src/features/competition/mock'
import { applyClassContribution, gradeQuiz, nextClassGap, rankClasses } from '../src/features/competition/logic'

async function demo(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Заглянуть в демо 9Б' }).click()
}
async function answer(page: Page, index: number, correct = true) {
  const question = knowledgeQuiz.questions[index]
  await expect(page.getByRole('progressbar', { name: 'Прогресс квиза' })).toHaveAttribute('aria-valuenow', String(index + 1))
  const option = question.options.find(o => correct ? o.id === question.correctOptionId : o.id !== question.correctOptionId)!
  await page.locator('.quiz-answer-options').getByRole('button', { name: new RegExp(option.text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')) }).click()
}
async function complete(page: Page, correctCount = 8) {
  await page.getByRole('button', { name: 'Пройти квиз', exact: true }).click()
  for (let i = 0; i < knowledgeQuiz.questions.length; i++) await answer(page, i, i < correctCount)
  await expect(page.getByText('КВИЗ ПРОЙДЕН', { exact: true })).toBeVisible()
}
async function noOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
}

