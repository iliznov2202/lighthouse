test('quiz: interruption resumes the next question; closing the event prevents new answers', async ({ page }, testInfo) => {
  await demo(page)
  await page.getByRole('button', { name: 'Пройти квиз', exact: true }).click()
  for (let i = 0; i < 3; i++) await answer(page, i)
  await page.reload()
  await page.getByRole('button', { name: 'Продолжить квиз', exact: true }).click()
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '4')
  await page.screenshot({ path: `artifacts/quiz-question-${testInfo.project.name}.png`, fullPage: true })
  await page.getByRole('button', { name: 'Демо события', exact: true }).click()
  await page.getByRole('button', { name: /^Последние сутки/ }).click()
  await page.getByRole('button', { name: 'К ленте', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Еженедельный квиз' })).toContainText('До конца: 24 часа')
  await page.getByRole('button', { name: 'Вся школа', exact: true }).click()
  await expect(page.locator('.post-card').filter({ hasText: 'До конца квиза осталось 24 часа' })).toHaveCount(1)
  await page.getByRole('button', { name: 'Продолжить квиз', exact: true }).click()
  await page.getByRole('button', { name: 'Демо события', exact: true }).click()
  await page.getByRole('button', { name: /^Квиз завершён Итоги/ }).click()
  await expect(page.locator('.competition-final-summary')).toContainText('9Б занял 2 место')
  await expect(page.locator('.competition-final-summary')).toContainText('Ты не проходил квиз этой недели')
  await expect(page.getByRole('button', { name: 'Пройти квиз', exact: true })).toHaveCount(0)
  await page.setViewportSize({ width: 320, height: 740 })
  await noOverflow(page)
  await page.getByRole('button', { name: 'К ленте', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Квиз завершён', exact: true })).toBeDisabled()
  await noOverflow(page)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Квиз завершён', exact: true })).toBeDisabled()
  const attempt = await page.evaluate(() => Object.values(JSON.parse(localStorage.getItem('mayak-competitions-v1')!))[0])
  expect(attempt).toMatchObject({ phase: 'finished', result: null, answers: [{}, {}, {}] })
})

