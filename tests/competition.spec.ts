test('scoring uses event rules and unique valid answers; ties and contributions remain stable', () => {
  const answers = knowledgeQuiz.questions.slice(0, 8).map(q => ({ questionId: q.id, optionId: q.correctOptionId }))
  const result = gradeQuiz(knowledgeQuiz, weeklyCompetition, [...answers, answers[0], { questionId: 'missing', optionId: 'a' }], initialClassRankings, 'class-9b', 'test')
  expect(result).toMatchObject({ correct: 8, personalPoints: 800, classPoints: 8, positionBefore: 4, positionAfter: 3 })
  expect(result.answers).toHaveLength(8)
  const once = applyClassContribution(initialClassRankings, result)
  expect(applyClassContribution(initialClassRankings, result)).toEqual(once)
  expect(nextClassGap(rankClasses(once), 'class-9b')).toMatchObject({ className: '8Б', points: 6, position: 2 })
  expect(initialClassRankings.find(c => c.classId === 'class-9b')?.points).toBe(157)
  const otherRules = gradeQuiz({ ...knowledgeQuiz, id: 'another-quiz', questions: knowledgeQuiz.questions.slice(0, 2) }, { ...weeklyCompetition, id: 'another-event', scoring: { personalPerCorrect: 25, classPerCorrect: 2 } }, answers, initialClassRankings, 'class-9b', 'test')
  expect(otherRules).toMatchObject({ total: 2, correct: 2, personalPoints: 50, classPoints: 4, positionAfter: 3 })
  const tied = rankClasses(initialClassRankings.map(c => c.classId === 'class-9b' ? { ...c, points: 161 } : c))
  expect(tied.filter(c => c.points === 161).map(c => c.position)).toEqual([3, 3])
})

test('another selected class starts at zero and receives only its own contribution', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Заглянуть в демо 9Б' })).toBeVisible()
  await page.evaluate(() => {
    const profile = JSON.parse(localStorage.getItem('mayak-profile-v1')!)
    localStorage.setItem('mayak-onboarded-v1', 'true')
    localStorage.setItem('mayak-profile-v1', JSON.stringify({ ...profile, className: '7А' }))
  })
  await page.reload()
  await expect(page.getByRole('region', { name: 'Еженедельный квиз' })).toContainText('7А')
  await complete(page, 2)
  await expect(page.locator('.quiz-result-score')).toHaveText('2из 10')
  await page.getByRole('button', { name: 'Посмотреть рейтинг', exact: true }).click()
  await expect(page.locator('[data-class-id="class-7А"] .ranking-points')).toHaveText('2')
  await expect(page.locator('[data-class-id="class-9b"] .ranking-points')).toHaveText('157')
  await page.getByRole('button', { name: 'Ученики', exact: true }).click()
  await expect(page.locator('.student-row')).toHaveCount(1)
  await expect(page.locator('[data-student-id="current-student"] .ranking-points')).toHaveText('200')
})
